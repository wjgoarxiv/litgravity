#!/usr/bin/env python3
"""
init_research.py: scaffold an autoresearch research directory for LitGravity.

Usage:
    python3 init_research.py --goal "..." --metric "..." --direction {maximize|minimize} \
        [--target "..."] [--max-iterations 20] [--model-call-cap 0] [--yes] \
        [--output .litgravity/evidence/<slug>/autoresearch/]

The scaffold is INCOMPLETE on purpose: it keeps labeled placeholders that the approved run fills
and validates before the baseline. Python 3.8+ standard library only. Exit codes: 0 scaffold
written, 1 refused (symlink, special file, declined reinitialisation), 2 usage error.
"""

